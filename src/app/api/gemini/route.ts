const TELEGRAM_BOT_TOKEN = "8994358206:AAHUpoHpMpqdnTxA_J30-xMipDg4l0vhBV8";
const TELEGRAM_CHAT_ID = "5195615040";

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL || "";
